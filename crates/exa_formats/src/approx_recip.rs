//! The approximate reciprocal and reciprocal square root (`RCPSS`/`RCPPS`,
//! `RSQRTSS`/`RSQRTPS`) as one fixed software answer.
//!
//! The original runs the processor's instructions, which are only specified
//! to about 12 bits: Intel and AMD processors return different values, so
//! the original itself does not repeat across machines. Exarust answers
//! them with one fixed table equal to an Intel processor's results (an
//! Intel Coffee Lake, checked over every 32-bit input), so runs repeat on
//! every machine (decision DEC-7).
//!
//! Intel's answer depends only on the top 11 bits of the input's
//! significand side: for the reciprocal the 11 high mantissa bits, for the
//! reciprocal square root the exponent's parity and the 10 high mantissa
//! bits. Each table holds those 2048 answers for an input in `[1, 2)`
//! (reciprocal) or `[0.5, 2)` (reciprocal square root), as the result's
//! low exponent bit and its 12 high mantissa bits; the input's exponent
//! then scales the result. The edges are the instructions': a NaN comes
//! back quiet, a zero or denormal input gives infinity of its sign, an
//! infinity gives a zero of its sign (the square root's negative infinity
//! and any other negative input give the default NaN), and a reciprocal
//! below the normal range is flushed to a zero of its sign. Neither
//! instruction reads the rounding or flush modes.

/// The default NaN the processor returns for an invalid input.
const DEFAULT_NAN: u32 = 0xFFC0_0000;

/// A table entry back to the result's bits for the reference exponent.
const fn entry(packed: u16) -> u32 {
    0x3F00_0000 | ((packed as u32) << 11)
}

/// The edges both instructions share, or `None` for a normal input that
/// goes through the table.
fn special(bits: u32, square_root: bool) -> Option<u32> {
    let sign = bits & 0x8000_0000;
    let exponent = (bits >> 23) & 0xFF;
    let mantissa = bits & 0x7F_FFFF;
    if exponent == 0xFF {
        return Some(if mantissa != 0 {
            bits | 0x40_0000
        } else if square_root && sign != 0 {
            DEFAULT_NAN
        } else {
            sign
        });
    }
    if exponent == 0 {
        return Some(sign | 0x7F80_0000);
    }
    if square_root && sign != 0 {
        return Some(DEFAULT_NAN);
    }
    None
}

/// `RSQRTSS`: the approximate reciprocal square root, Intel's answer.
#[inline]
pub fn reciprocal_sqrt(value: f32) -> f32 {
    let bits = value.to_bits();
    if let Some(edge) = special(bits, true) {
        return f32::from_bits(edge);
    }
    let exponent = (bits >> 23) & 0xFF;
    let parity = exponent & 1;
    let key = (parity << 10) | ((bits >> 13) & 0x3FF);
    let reference = entry(RSQRT_TABLE[key as usize]);
    // The table's input has exponent 126 + parity; rsqrt(4^k x) = rsqrt(x) / 2^k.
    let shift = (exponent as i32 - (126 + parity as i32)) / 2;
    f32::from_bits((reference as i32 - (shift << 23)) as u32)
}

/// `RCPSS`: the approximate reciprocal, Intel's answer.
#[inline]
pub fn reciprocal(value: f32) -> f32 {
    let bits = value.to_bits();
    if let Some(edge) = special(bits, false) {
        return f32::from_bits(edge);
    }
    let sign = bits & 0x8000_0000;
    let exponent = ((bits >> 23) & 0xFF) as i32;
    let reference = entry(RCP_TABLE[((bits >> 12) & 0x7FF) as usize]);
    // The table's input has exponent 127; rcp(2^k x) = rcp(x) / 2^k.
    let result_exponent = ((reference >> 23) & 0xFF) as i32 - (exponent - 127);
    if result_exponent <= 0 {
        return f32::from_bits(sign);
    }
    f32::from_bits(sign | ((result_exponent as u32) << 23) | (reference & 0x7F_FFFF))
}

/// `RCPPS`: [`reciprocal`] of each lane.
#[inline]
pub fn reciprocal4(values: [f32; 4]) -> [f32; 4] {
    values.map(reciprocal)
}

/// `RSQRTPS`: [`reciprocal_sqrt`] of each lane.
#[inline]
pub fn reciprocal_sqrt4(values: [f32; 4]) -> [f32; 4] {
    values.map(reciprocal_sqrt)
}

